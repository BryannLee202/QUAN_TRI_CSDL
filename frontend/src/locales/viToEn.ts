function escapeRegExp(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// Sắp xếp từ dài đến ngắn để cụm dài luôn được ưu tiên dịch trước
const SORTED_PAIRS = [...VI_TO_EN_EXACT].sort((a, b) => b[0].length - a[0].length);

// Tiền biên dịch RegExp có ranh giới từ tiếng Việt/Anh (tương thích ES5, không bao giờ dịch cắt ngang từ)
const WORD_CHAR_CLASS = "[A-Za-z0-9\\u00C0-\\u024F\\u1E00-\\u1EFF]";
const WORD_START_RE = new RegExp(`^${WORD_CHAR_CLASS}`);
const WORD_END_RE = new RegExp(`${WORD_CHAR_CLASS}$`);

const COMPILED_EXACT_REGEXES: Array<[RegExp, string]> = SORTED_PAIRS.map(([vi, en]) => {
  const startsWord = WORD_START_RE.test(vi);
  const endsWord = WORD_END_RE.test(vi);
  const prefix = startsWord ? `(?<!${WORD_CHAR_CLASS})` : "";
  const suffix = endsWord ? `(?!${WORD_CHAR_CLASS})` : "";
  return [new RegExp(`${prefix}${escapeRegExp(vi)}${suffix}`, "gi"), en];
});

export function translateTextViToEn(input: string): string {
  if (!input || !input.trim()) return input;

  // Chuẩn hóa xuống dòng và nhiều khoảng trắng trong JSX đa dòng thành 1 khoảng trắng trước khi dịch
  const lead = /^\s/.test(input) ? " " : "";
  const trail = /\s$/.test(input) ? " " : "";
  let out = input.trim().replace(/\s+/g, " ");

  // 1. Mẫu động có số lượng / mã định danh
  out = out
    .replace(/\bKhay\s+(R\d{2}-\d{3})\b/gi, "Tray $1")
    .replace(/\bKệ\s+(\d{2})\s*•\s*Tầng\s+(\d{2})\b/gi, "Rack $1 • Shelf $2")
    .replace(/\bKệ\s+(\d{2})\b/gi, "Rack $1")
    .replace(/\bBuồng\s+(RM\d+|B-\d+)\b/gi, "Room $1")
    .replace(/\bNgày\s+(\d+-\d+)\b/gi, "Day $1")
    .replace(/\b(\d+)\s+Ngày\b/gi, "$1 Days")
    .replace(/\b(\d+)\s+Giờ\b/gi, "$1 Hours")
    .replace(/\b(\d+)\s+Phút\b/gi, "$1 Mins")
    .replace(/\b(\d+)\s+Tháng\b/gi, "$1 Months")
    .replace(/\b(\d+)\s+Khay\b/gi, "$1 Trays")
    .replace(/\b(\d+)\s+Buồng\b/gi, "$1 Chambers")
    .replace(/\bĐạt\s+(\d+)%\s+chu kỳ\b/gi, "$1% Cycle Progress")
    .replace(/\bKhay trên Kệ\s+(\d{2}):/gi, "Trays on Rack $1:")
    .replace(/\bRadar Ống Kính Kệ\s+(\d{2}):/gi, "Rack $1 Lens Radar:")
    .replace(/\bCảm Biến Tại Kệ\s+(\d{2})\s*•\s*Tầng\s+(\d{2})/gi, "Sensors at Rack $1 • Shelf $2")
    .replace(/\bVị trí ray:\s*(\d+)%\s*\/\s*100%/gi, "Rail Pos: $1% / 100%")
    .replace(/\bTọa độ ray:\s*(\d+)%\s*\/\s*100%/gi, "Rail Pos: $1% / 100%");

  // 2. Thay thế chính xác với ranh giới từ Unicode & không phân biệt hoa/thường
  for (const [regex, en] of COMPILED_EXACT_REGEXES) {
    out = out.replace(regex, en);
  }

  return `${lead}${out}${trail}`;
}
